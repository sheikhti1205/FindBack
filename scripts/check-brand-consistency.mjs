import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {readFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {resolve} from 'node:path';
const root=fileURLToPath(new URL('../',import.meta.url));
const brand='apps/mobile/src/assets/brand',res='apps/mobile/android/app/src/main/res';
const masterSha='27c4f0479e5240b549183731d4302633c31734a405d1bdf2cc154543ebcc0b4d';
const token='birdleaf-v1';
const sha=b=>createHash('sha256').update(b).digest('hex');
export function checkBrandConsistency({read=path=>readFileSync(resolve(root,path))}={}) {
 const text=path=>read(path).toString('utf8');
 const manifest=JSON.parse(text(`${brand}/generated-brand-manifest.json`));
 assert.equal(manifest.generation,token);
 assert.equal(manifest.master.path,`${brand}/brand-tile-master.png`);
 assert.equal(manifest.master.sha256,masterSha);
 assert.equal(sha(read(manifest.master.path)),masterSha,'owner master changed');
 assert.equal(manifest.generator.path,'scripts/generate-brand-assets.py');
 assert.equal(sha(read(manifest.generator.path)),manifest.generator.sha256,'generator differs; regenerate outputs');
 const expected=[];
 for(const shape of ['mark','tile'])for(const v of ['dark','light'])expected.push(`${brand}/brand-${shape}-${v}.png`);
 for(const n of [16,32,48,180,192,512])expected.push(`apps/mobile/public/icons/findback-${token}-${n}.png`);
 for(const n of ['findback-192.png','findback-512.png','apple-touch-icon.png'])expected.push(`apps/mobile/public/icons/${n}`);
 expected.push('apps/mobile/public/favicon.ico');
 for(const d of ['mdpi','hdpi','xhdpi','xxhdpi','xxxhdpi']){
  for(const n of ['ic_launcher','ic_launcher_round','ic_launcher_foreground'])expected.push(`${res}/mipmap-${d}/${n}.png`);
  for(const n of ['ic_launcher_monochrome','ic_stat_findback','brand_splash_icon'])expected.push(`${res}/drawable-${d}/${n}.png`);
  for(const orientation of ['port','land'])expected.push(`${res}/drawable-${orientation}-${d}/splash.png`);
 }
 expected.push(`${res}/drawable/splash.png`);
 assert.deepEqual(Object.keys(manifest.outputs).sort(),expected.sort(),'generated inventory incomplete');
 for(const [path,record] of Object.entries(manifest.outputs)){
  const bytes=read(path);assert.equal(sha(bytes),record.sha256,`generated bytes differ: ${path}`);
  if(path.endsWith('.png')){
   assert.equal(bytes.subarray(0,8).toString('hex'),'89504e470d0a1a0a');
   assert.equal(bytes.readUInt32BE(16),record.width,path);assert.equal(bytes.readUInt32BE(20),record.height,path);
  }else{assert.equal(bytes.readUInt16LE(2),1);assert.equal(bytes.readUInt16LE(4),3);}
 }
 const html=text('apps/mobile/index.html');
 for(const n of [16,32,48,180])assert.ok(html.includes(`/icons/findback-${token}-${n}.png`),`HTML missing ${n}`);
 assert.match(html,/sizes="16x16"/);assert.match(html,/sizes="32x32"/);assert.match(html,/rel="apple-touch-icon" sizes="180x180"/);
 assert.doesNotMatch(html,/\/icons\/(?:findback-(?:192|512)|apple-touch-icon)\.png/);
 assert.ok(html.includes(`https://findbackapp.social/icons/findback-${token}-512.png`),'static public social image');
 for(const path of ['drawable/ic_stat_findback.xml','drawable-v24/ic_launcher_foreground.xml']){
  let exists=false;try{read(`${res}/${path}`);exists=true;}catch(error){if(error.code!=='ENOENT')throw error;}
  assert.equal(exists,false,`competing legacy art: ${path}`);
 }
 for(const name of ['ic_launcher','ic_launcher_round']){
  const xml=text(`${res}/mipmap-anydpi-v26/${name}.xml`);
  for(const ref of ['@mipmap/ic_launcher_foreground','@drawable/ic_launcher_monochrome','@color/ic_launcher_background'])assert.ok(xml.includes(ref));
 }
 const styles=text(`${res}/values/styles.xml`);
 assert.match(styles,/<item name="windowSplashScreenAnimatedIcon">@drawable\/brand_splash_icon<\/item>/);
 const android=text('apps/mobile/android/app/src/main/AndroidManifest.xml');
 assert.ok(android.includes('android:icon="@mipmap/ic_launcher"'));
 assert.ok(android.includes('android:roundIcon="@mipmap/ic_launcher_round"'));
 assert.match(android,/com.google.firebase.messaging.default_notification_icon[\s\S]*?@drawable\/ic_stat_findback/);
 const presenter=text('apps/mobile/android/app/src/main/java/com/findback/app/push/NotificationPresenter.kt');
 assert.equal((presenter.match(/setSmallIcon\(R.drawable.ic_stat_findback\)/g)??[]).length,3);
 for(const screen of ['HomeTopBar','Splash','About'])assert.ok(text(`apps/mobile/src/screens/${screen}.tsx`).includes('<BrandMark'));
 const auth=text('apps/mobile/src/components/auth/AuthShell.tsx');
 assert.ok(auth.includes('<BrandMark'),'shared auth must use canonical brand');
 assert.doesNotMatch(auth,/\bRadar\b|<svg|assets\/brand\//,'shared auth must not substitute or clone the mark');
 assert.ok(text('apps/mobile/src/screens/Onboarding.tsx').includes('<BrandMark'));
 assert.doesNotMatch(text('apps/mobile/src/App.tsx'),/PublicLanding|RecoveryDemo/,'app root must not revive the rejected landing');
 const share=text('apps/share-preview/handler.cjs');
 assert.ok(share.includes(`/icons/findback-${token}-32.png`));
 return {outputs:expected.length,generation:token};
}
if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url)){
 try{console.log('Brand consistency PASS',JSON.stringify(checkBrandConsistency()));}
 catch(error){console.error(error.message);process.exitCode=1;}
}
